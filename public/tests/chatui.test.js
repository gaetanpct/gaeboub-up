const fs = require("fs");
const { JSDOM } = require("jsdom");
const P = require("path").join(__dirname, "..", "public") + "/";
const { GameEngine } = require(P + "game/engine.js");
let fail = 0;
const ok = (c, m) => { if (!c) { fail++; console.log("ECHEC", m); } else console.log("ok", m); };
const e = new GameEngine(["Ana", "Ben", "Bot"], { aiPlayerIds: [2] });
const html = fs.readFileSync(P + "index.html", "utf8").replace(/<script[^>]*src=[^>]*><\/script>/g, "");
const dom = new JSDOM(html, { runScripts: "outside-only", pretendToBeVisual: true, url: "http://localhost/" });
const w = dom.window; const handlers = {}; const emitted = [];
w.io = () => ({ id: "s", on: (ev, fn) => (handlers[ev] = fn), emit: (ev, p) => emitted.push([ev, p]) });
for (const f of ["sounds.js", "game/rules-schema.js", "game/powers.js", "game/world-events.js", "game/insurance-plans.js", "board-view.js", "game.js"]) w.eval(fs.readFileSync(P + f, "utf8"));
handlers["game:started"]({ state: e.getPublicState(), socketToPlayerId: { s: 0 }, settings: {} });
const $ = (id) => w.document.getElementById(id);
ok($("chat-panel").hidden, "tchat réduit par défaut");
handlers["chat:message"]({ id: 1, from: 1, fromName: "Ben", to: null, toName: null, text: "<b>hey</b>", ts: 1 });
handlers["chat:message"]({ id: 2, from: 1, fromName: "Ben", to: 0, toName: "Ana", text: "psst", ts: 2 });
ok(!$("chat-badge").hidden && $("chat-badge").textContent === "2", "pastille 2 non lus");
ok($("chat-toggle").classList.contains("chat-toggle--pulse"), "effet visuel");
$("chat-toggle").click();
ok(!$("chat-panel").hidden && $("chat-badge").hidden, "ouverture remet le compteur à zéro");
ok($("chat-messages").querySelector("b") === null && $("chat-messages").textContent.includes("<b>hey</b>"), "HTML non interprété");
ok($("chat-messages").textContent.includes("(privé)"), "privé signalé");
const opts = [...$("chat-recipient").options].map((o) => o.textContent);
ok(opts.join(",") === "Tous,Ben", "destinataires : Tous + humains (ni moi, ni l'IA) -> " + opts.join(","));
$("chat-recipient").value = "1"; $("chat-input").value = "coucou";
$("chat-form").dispatchEvent(new w.Event("submit", { cancelable: true }));
const sent = emitted.find((x) => x[0] === "chat:send");
ok(sent && sent[1].text === "coucou" && sent[1].toPlayerId === 1, "envoi privé vers Ben");
handlers["chat:message"]({ id: 3, from: 0, fromName: "Ana", to: null, text: "moi", ts: 3 });
ok($("chat-badge").hidden, "mes propres messages ne comptent pas comme non lus");
process.exit(fail ? 1 : 0);
